export function translateUi(language: UiLanguage, message: string, ...values: UiTextValue[]) {
  const pattern = language === 'English' ? (english[message] ?? message) : message
  return values.length
    ? pattern.replace(/\{(\d+)\}/g, (_, index: string) => String(values[Number(index)] ?? ''))
    : pattern
}
